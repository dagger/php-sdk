<?php

declare(strict_types=1);

namespace Dagger\Module;

use Closure;
use Dagger\Service\NormalizesClassName;
use Dagger\TypeDefKind;
use Dagger\ValueObject\Argument;
use Dagger\ValueObject\DaggerEnum;
use Dagger\ValueObject\DaggerFunction;
use Dagger\ValueObject\DaggerObject;
use Dagger\ValueObject\ListOfType;
use Dagger\ValueObject\Type;
use RuntimeException;

final readonly class DangEntrypointRenderer
{
    private const HEADER = "# Code generated by dagger. DO NOT EDIT.\n";

    /**
     * PHP cannot name these classes as the schema names their types.
     */
    private const SCHEMA_NAMES = [
        'Function_' => 'Function',
        'Id' => 'ID',
        'Json' => 'JSON',
    ];

    public static function write(
        Description $description,
        string $moduleName,
        string $clientVersion,
        string $output,
        ?Closure $enumMemberNames = null,
        array $outside = [],
        array $exclude = [],
    ): void {
        if (!is_dir($output) && !mkdir($output, 0755, true)) {
            throw new RuntimeException("Cannot create the directory $output");
        }

        file_put_contents("$output/types.dang", self::renderTypes($description, $moduleName, $enumMemberNames));
        file_put_contents("$output/main.dang", self::renderMain($clientVersion, $outside, $exclude));
    }

    /**
     * @param ?Closure(list<string>): list<string> $enumMemberNames The engine's
     *     enum member names, in input order, where the engine can answer.
     */
    public static function renderTypes(
        Description $description,
        string $moduleName,
        ?Closure $enumMemberNames = null,
    ): string {
        $entries = [
            ...array_map(
                static fn($object) => self::object($object, $moduleName),
                $description->objects,
            ),
            ...array_map(
                static fn($enum) => self::enum($enum, $enumMemberNames),
                $description->enums,
            ),
        ];

        $body = '';
        foreach ($entries as $lines) {
            $body .= '      ' . implode("\n      ", $lines) . ",\n";
        }

        return self::HEADER . "\ntype ModuleTypes {\n  pub all: [TypeDef!]! {\n    [\n"
            . $body . "    ]\n  }\n}\n";
    }

    /**
     * @param list<string> $outside Directories outside the module that its
     *     Composer setup reads, relative to the module.
     * @param list<string> $exclude Patterns, relative to the module, that the
     *     build leaves out.
     */
    public static function renderMain(string $clientVersion, array $outside = [], array $exclude = []): string
    {
        $sources = implode('', array_map(
            static fn($path) => '      .withDirectory(workspace.cwd + ' . self::quote("/$path")
                . ', workspace.directory(' . self::quote($path) . ', exclude: ' . self::SOURCES_EXCLUDE
                . ", gitignore: true))\n",
            $outside,
        ));

        return self::HEADER . strtr(self::MAIN, [
            '%clientVersion%' => self::quote($clientVersion),
            "%sources%\n" => $sources,
            '%exclude%' => self::SOURCES_EXCLUDE,
            '%buildExclude%' => '[' . implode(', ', array_map(self::quote(...), $exclude)) . ']',
        ]);
    }

    /** @return list<string> */
    private static function object(DaggerObject $object, string $moduleName): array
    {
        $name = NormalizesClassName::trimLeadingNamespace($object->name);
        $isInterface = $object->isInterface();
        $lines = ['typeDef.' . ($isInterface ? 'withInterface' : 'withObject') . '(' . self::quote($name)
            . self::option('description', $object->description) . ')'];

        foreach ($object->daggerFields as $field) {
            $lines[] = '  .withField(' . self::quote($field->name) . ', ' . self::type($field->type, refuseInterfaces: true)
                . self::option('description', $field->description) . ')';
        }

        foreach ($object->daggerFunctions as $function) {
            if (!$function->isConstructor()) {
                array_push($lines, ...self::wrap('withFunction', self::function($function)));
            }
        }

        // The engine finds an entrypoint's main object by its constructor, even
        // for an object with neither fields nor one of its own, and refuses more
        // than one constructor. Only the main object's is ever called.
        if (!$isInterface && self::isMainObject($name, $moduleName)) {
            $constructor = $object->daggerFunctions[''] ?? null;
            $function = $constructor !== null
                ? self::function($constructor)
                : ['function("", ' . self::type(new Type($object->name)) . ')'];
            array_push($lines, ...self::wrap('withConstructor', $function));
        }

        return $lines;
    }

    private static function isMainObject(string $name, string $moduleName): bool
    {
        $normalize = static fn(string $value) => strtolower(preg_replace('/[^a-zA-Z0-9]/', '', $value));

        return $normalize($name) === $normalize($moduleName);
    }

    /** @return list<string> */
    private static function enum(DaggerEnum $enum, ?Closure $enumMemberNames): array
    {
        self::refuseCollidingCases($enum, $enumMemberNames);

        $name = NormalizesClassName::trimLeadingNamespace($enum->name);
        $lines = ['typeDef.withEnum(' . self::quote($name) . self::option('description', $enum->description) . ')'];

        foreach ($enum->cases as $case) {
            $lines[] = '  .withEnumMember(' . self::quote($case->name)
                . self::option('value', $case->value)
                . self::option('description', $case->description) . ')';
        }

        return $lines;
    }

    /**
     * The engine replaces a member that has the name of an earlier one without
     * an error, which would lose a PHP case from the module. Names are escaped
     * because two that collide can differ only in invisible bytes.
     */
    private static function refuseCollidingCases(DaggerEnum $enum, ?Closure $enumMemberNames): void
    {
        $visible = static fn(string $name) => addcslashes($name, "\x80..\xff");
        $cases = array_map(static fn($case) => $case->name, $enum->cases);
        $names = $enumMemberNames === null
            ? array_map(EngineNaming::enumMemberName(...), $cases)
            : $enumMemberNames($cases);
        $seen = [];
        foreach ($cases as $i => $case) {
            $name = $names[$i];
            if (isset($seen[$name])) {
                throw new RuntimeException(sprintf(
                    'Enum %s cannot be registered: the engine gives its cases %s and %s the same name, %s. Rename one.',
                    $enum->name,
                    $visible($seen[$name]),
                    $visible($case),
                    $visible($name),
                ));
            }
            $seen[$name] = $case;
        }
    }

    /** @return list<string> */
    private static function function(DaggerFunction $function): array
    {
        $lines = ['function(' . self::quote($function->name) . ', ' . self::type($function->returnType, refuseInterfaces: true) . ')'];

        if ($function->description !== null && $function->description !== '') {
            $lines[] = '  .withDescription(' . self::quote($function->description) . ')';
        }

        if ($function->withCheck) {
            $lines[] = '  .withCheck';
        }

        if ($function->withGenerator) {
            $lines[] = '  .withGenerator';
        }

        if ($function->withUp) {
            $lines[] = '  .withUp';
        }

        if ($function->withAgent) {
            $lines[] = '  .withAgent';
        }

        foreach ($function->arguments as $argument) {
            $lines[] = '  ' . self::argument($argument);
        }

        return $lines;
    }

    private static function argument(Argument $argument): string
    {
        $line = '.withArg(' . self::quote($argument->name) . ', ' . self::type($argument->type)
            . self::option('description', $argument->description);

        // An optional type already reads as a null default, and the engine does
        // not apply a default path to an argument that has a default value.
        $default = $argument->default === null ? 'null' : (string) $argument->default;
        if ($default !== 'null') {
            $line .= ', defaultValue: (' . self::quote($default) . ' :: Dagger.JSON!)';
        }

        $line .= self::option('defaultPath', $argument->defaultPath);

        if ($argument->ignore !== null) {
            $line .= ', ignore: [' . implode(', ', array_map(self::quote(...), $argument->ignore)) . ']';
        }

        return $line . ')';
    }

    private static function type(ListOfType|Type $type, bool $refuseInterfaces = false): string
    {
        $base = $type->nullable ? 'typeDef.withOptional(true)' : 'typeDef';

        if ($type instanceof ListOfType) {
            return "$base.withListOf(" . self::type($type->subtype, $refuseInterfaces) . ')';
        }

        // The entrypoint declares no dependencies, so the engine would not know a client's types.
        if (preg_match('#^\\\\?Dagger\\\\Clients\\\\([^\\\\]+)\\\\#', $type->name, $client) === 1) {
            throw new RuntimeException(sprintf(
                'The type %s comes from the module client %s, and a module function cannot take or return a client type yet',
                $type->name,
                $client[1],
            ));
        }

        return match ($type->typeDefKind) {
            TypeDefKind::BOOLEAN_KIND,
            TypeDefKind::FLOAT_KIND,
            TypeDefKind::INTEGER_KIND,
            TypeDefKind::STRING_KIND,
            TypeDefKind::VOID_KIND => "$base.withKind(TypeDefKind.{$type->typeDefKind->name})",
            TypeDefKind::SCALAR_KIND => "$base.withScalar(" . self::quote(self::schemaName($type->name)) . ')',
            TypeDefKind::ENUM_KIND => "$base.withEnum("
                . self::quote(NormalizesClassName::trimLeadingNamespace($type->name)) . ')',
            TypeDefKind::OBJECT_KIND => "$base.withObject(" . self::quote(
                $type->isIdable()
                    ? self::schemaName($type->name)
                    : NormalizesClassName::trimLeadingNamespace($type->name),
            ) . ')',
            TypeDefKind::INTERFACE_KIND => !$refuseInterfaces && $type->isDaggerInterface()
                ? "$base.withInterface(" . self::quote(NormalizesClassName::trimLeadingNamespace($type->name)) . ')'
                : throw new RuntimeException(sprintf('Currently cannot handle custom interfaces: %s', $type->name)),
            default => throw new RuntimeException("No support exists for $type->name"),
        };
    }

    private static function schemaName(string $class): string
    {
        $short = NormalizesClassName::shorten($class);

        return self::SCHEMA_NAMES[$short] ?? $short;
    }

    private static function option(string $name, ?string $value): string
    {
        return $value === null || $value === '' ? '' : ", $name: " . self::quote($value);
    }

    private static function quote(string $value): string
    {
        return json_encode($value, JSON_THROW_ON_ERROR | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE);
    }

    /**
     * @param list<string> $body
     * @return list<string>
     */
    private static function wrap(string $call, array $body): array
    {
        return [
            "  .$call(",
            ...array_map(static fn($line) => "    $line", $body),
            '  )',
        ];
    }

    private const SOURCES_EXCLUDE = '["**/.git", "vendor"]';

    private const MAIN = <<<'DANG'

    type Entrypoint implements ModuleEntrypoint {
      pub sources(workspace: Workspace!): Directory! {
        directory
    %sources%
          .withDirectory(workspace.cwd, workspace.directory(".", exclude: %exclude%, gitignore: true))
      }

      pub types: [TypeDef!]! {
        ModuleTypes().all
      }

      pub call(
        receiverType: String!,
        receiverValue: JSON,
        fnName: String!,
        fnArgs: JSON!,
        callDigest: String,
      ): JSON! {
        let request = JSON.encode({{
          receiverType: receiverType,
          receiverValue: receiverValue,
          fnName: fnName,
          fnArgs: fnArgs,
        }})
        let result = runtime
          .withEnvVariable("DAGGER_CLIENT_VERSION", %clientVersion%)
          # The exec is cached on its own recipe, which holds neither the call's
          # arguments nor its cache policy; the engine's digest of the call does
          # (dagger/dagger#14491), so a policy reaches the exec through it.
          .withEnvVariable("DAGGER_MODULE_CALL_DIGEST", callDigest ?? "")
          .withExec(["php", "sdk/bin/dagger-module", "call", "--output", "/dagger/result.json"], stdin: request, experimentalPrivilegedNesting: true)
          .file("/dagger/result.json")
          .contents rescue {
            # From v1.0.0-beta.27 an exec error's message carries only the exit code.
            # Its extensions hold the stderr, capped by the engine at 100 KiB.
            err: GraphQLError => {
              let stderr = (JSON.decode(err.extensions) :: {{stderr: String}}).stderr ?? ""
              if (stderr == "") { raise err }
              raise stderr
            }
          }
        (result :: JSON!)
      }

      let runtime: Container! {
        PhpModuleBuild(contextDir: currentModule.contextDirectory, subPath: currentModule.sourceSubpath, exclude: %buildExclude%).installed
      }
    }

    DANG;
}
