<?php

namespace Dagger\Codegen;

use Nette\PhpGenerator\ClassType;
use Nette\PhpGenerator\EnumType;
use Nette\PhpGenerator\InterfaceType;
use Nette\PhpGenerator\PhpFile;
use Nette\PhpGenerator\PsrPrinter;
use RuntimeException;

class CodeWriter
{
    public const NAMESPACE = 'Dagger';

    public function __construct(private readonly string $targetDirectory)
    {
        if (!is_dir($targetDirectory) && !mkdir($targetDirectory, 0755, true)) {
            throw new RuntimeException("Cannot create the directory $targetDirectory");
        }
    }

    public function write(EnumType|ClassType|InterfaceType $classType): void
    {
        $phpFile = new PhpFile();
        $phpFile->setStrictTypes(true);
        $phpFile->addNamespace(self::NAMESPACE)->add($classType);
        $phpFile->addComment('This class has been generated by dagger-php-sdk. DO NOT EDIT.');

        $filePath = implode(DIRECTORY_SEPARATOR, [
           $this->targetDirectory,
           $classType->getName() . '.php',
        ]);

        $printer = new PsrPrinter();

        // file_put_contents only warns when it fails, and a missing client would
        // otherwise surface far from here, as classes that do not exist.
        if (file_put_contents($filePath, $printer->printFile($phpFile)) === false) {
            throw new RuntimeException("Cannot write $filePath");
        }
    }
}
